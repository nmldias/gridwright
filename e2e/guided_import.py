#!/usr/bin/env python3
"""Guided import (Studio): a large export from raw rows to clean tables, analysis, a saved recipe,
a similar file with another layout, a keyed comparison of the two, tables placed in a workbook and
the right-click lineage — over synthetic invoice exports generated by e2e/guided_fixture.py, whose
expected figures are computed independently of the server.

  API      the first export is read and profiled; the proposed steps are previewed and run; the
           totals and monthly figures match the fixture; checks, insights, CSV export, placement,
           row lineage (original line ↔ cleaned row, paired by column); the steps saved as a recipe
  browser  the corrected re-export goes in through the Studio: the recipe is recognised despite the
           layout drift (title rows, a renamed and moved column, one dropped, one new), “What
           changed?” explains it, the run, then Related → Compare → place the comparison in a new
           workbook → right-click each placed table: “How was this made?”
  API      the comparison the person made is exact (status changes, corrected amounts and their net,
           documents only here / missing), the rows trace to the right file; an automatic recipe
           runs by itself on the next similar file; bad input and bad requests are refused; deleting
           a dataset removes it and leaves the placed tables in the workbook

Usage: python3 e2e/guided_import.py [http://127.0.0.1:8787]   (screenshots in $E2E_OUT)
"""
import json
import os
import sys
import time
import urllib.error
