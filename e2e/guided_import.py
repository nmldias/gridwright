os.makedirs(OUT, exist_ok=True)

results = []


def check(name, ok, detail=""):
    results.append((name, bool(ok), detail))
    print(("PASS " if ok else "FAIL ") + name + (f" — {str(detail)[:300]}" if detail not in ("", None) else ""), flush=True)


def call(method, path, body=None, raw=None, ctype="application/json"):
    data = raw if raw is not None else (json.dumps(body).encode() if body is not None else None)
    req = urllib.request.Request(BASE + path, data=data, method=method, headers={"content-type": ctype} if data is not None else {})
    try:
        with urllib.request.urlopen(req, timeout=300) as r:
            t = r.read()
            return r.status, (json.loads(t) if t and r.headers.get("content-type", "").startswith("application/json") else t)
    except urllib.error.HTTPError as e:
        t = e.read()
        try:
            return e.code, json.loads(t)
        except Exception:
            return e.code, t


def upload(name, buf):
    return call("POST", f"/api/datasets?name={urllib.parse.quote(name)}", raw=buf, ctype="application/octet-stream")


def wait(job, timeout=600):
    end = time.time() + timeout
    while time.time() < end:
        st, j = call("GET", f"/api/datasets/jobs/{job}")
        j = j["job"]
        if j["status"] in ("done", "failed"):
            return j
        time.sleep(0.5)
    raise SystemExit(f"job {job} did not finish")


def table(ds, run, key, merge=None):
    """every row of an output (pages of 500), as dicts"""
    rows, off = [], 0
    while True:
        path = f"/api/datasets/{ds}/merges/{merge}/table/{key}" if merge else f"/api/datasets/{ds}/runs/{run}/table/out_{key}"
        st, p = call("GET", f"{path}?offset={off}&limit=500")
        if st != 200:
            raise SystemExit(f"{path}: {st} {p}")
        rows += [dict(zip(p["columns"], r)) for r in p["rows"]]
        off += len(p["rows"])
        if off >= p["total"] or not p["rows"]:
            return rows


def ident(v):
    return str(v)[:-2] if isinstance(v, float) and v.is_integer() else str(v)


def near(a, b, tol=0.01):
    return a is not None and b is not None and abs(float(a) - float(b)) <= tol


def main():
    buf_a, buf_b, X = build()
    open(f"{OUT}/{NAME_A}.xlsx", "wb").write(buf_a)
    open(f"{OUT}/{NAME_B}.xlsx", "wb").write(buf_b)
    XA, XB, XC = X["a"], X["b"], X["compare"]
    # recipes left by an earlier run of this suite would claim the layout
    st, rr = call("GET", "/api/recipes")
    for r in rr.get("recipes", []):
        if r["name"].startswith("E2E guided"):
            call("DELETE", f"/api/recipes/{r['id']}")

    # ============================================================ 1. the first export, by the API
    t0 = time.time()
    st, r = upload(f"{NAME_A}.xlsx", buf_a)
    check("1. an XLSX export is accepted and read in the background", st == 201 and r.get("job"), st)
    A = r["dataset"]["id"]
    j = wait(r["job"]["id"])
    st, d = call("GET", f"/api/datasets/{A}")
    M, P = d["dataset"], d.get("proposal") or {}
    sheet = M["sheets"][0]
    check("1. every row is read", j["status"] == "done" and sheet["rows"] == XA["rows"] + 1 and sheet["cols"] == 12, (j["status"], sheet["rows"], sheet["cols"], f"{time.time() - t0:.1f}s"))
    found = " ".join(f["text"] for f in P.get("findings", []))
    check("2. the profile finds the header, the text amounts, the single currency and the positive credit notes",
          "header on row 1" in found and "Valor Total" in found and "1.234,56" in found and "AOA" in found and f"{XA['credit_notes']} credit notes" in found, found[:400])
    steps, roles = M["draft"]["steps"], M["draft"]["roles"]
    types = [s["type"] for s in steps]
    check("2. steps are proposed (by rule): header, conversion, signed amounts, cancelled left out, tables",
          M["draft"]["by"] == "proposer" and types[0] == "header" and {"convert", "signed", "filter", "table"} <= set(types), types)
    check("2. roles are recognised: document number, date, amount, customer (by name, with its code), status, unit",
          roles.get("id") == "no_interno" and roles.get("date") == "data_emissao" and roles.get("customerCode") == "codigo_cliente" and str(roles.get("customer", "")).startswith("cliente") and roles.get("status") == "status" and roles.get("unit") == "AOA", roles)
    st, pv = call("POST", f"/api/datasets/{A}/preview", {"steps": steps, "sample": 3000})
    bad = [x for x in pv.get("results", []) if x["status"] != "done"]
    check("3. the preview runs every step and reports what each did", st == 200 and pv.get("ok") and not bad and len(pv["results"]) == len(steps), bad[:2])
    sg = next((x for x in pv["results"] if x["id"] == next(s["id"] for s in steps if s["type"] == "signed")), {})
    check("3. the signed-amount step says how many rows count negative", sg.get("changed") == XA["credit_notes"], sg.get("notes"))
    st, r = call("POST", f"/api/datasets/{A}/run", {"steps": steps, "roles": roles})
    j = wait(r["job"]["id"])
    RUN_A = j.get("result", {}).get("run")
    st, R = call("GET", f"/api/datasets/{A}/runs/{RUN_A}")
    R = R["run"]
    outs = {o["key"]: o for o in R["outputs"]}
    check("4. the full run succeeds: cancelled documents are left out, the rest kept", R["ok"] and R["rows"] == XA["kept"] and outs["documents"]["rows"] == XA["kept"], (R["ok"], R["rows"]))
    check("4. several tables come out of one sheet", {"documents", "monthly", "customers", "top_customers", "open_ageing", "exceptions"} <= set(outs), sorted(outs))
    docs = table(A, RUN_A, "documents")
    net = round(sum(x["net_amount"] for x in docs), 2)
    check("5. the net amount of the clean documents is the fixture's (credit notes negative, cancelled out)", near(net, XA["net"]), (net, XA["net"]))
    monthly = {x["month"]: x for x in table(A, RUN_A, "monthly")}
    check("5. month by month, the net amounts are the fixture's", sorted(monthly) == XA["months"] and all(near(monthly[m]["net_amount"], v) for m, v in XA["by_month"].items()),
          [(m, monthly.get(m, {}).get("net_amount"), v) for m, v in XA["by_month"].items() if not near(monthly.get(m, {}).get("net_amount"), v)][:3])
    check("5. no document number is read as a decimal", all(isinstance(x["no_interno"], int) or float(x["no_interno"]).is_integer() for x in docs[:50]))
    uniq = next((c for c in R["checks"] if "unique" in c["label"]), None)
    check("6. the checks run on every row (Nº interno unique)", uniq and uniq["failing"] == 0 and uniq["total"] == XA["rows"], uniq)
    ins = {i["id"]: i for i in (R.get("insights") or {}).get("items", [])}
    texts = " ".join(i["text"] for i in ins.values())
    check("7. insights: trend, concentration, credit notes, open receivables", len(ins) >= 5 and "Herfindahl" in texts and "Credit notes" in texts and "Aberta" in texts, sorted(ins))
    check("7. insight wording is sound when no new customer arrives", "()" not in texts and "0 new ones" not in texts)
    code, spelt = XA["variant"]
    st, MA = call("GET", f"/api/datasets/{A}")
    canon = next((s for s in MA["dataset"]["draft"]["steps"] if s["type"] == "canonical"), {})
    check("7. a customer code written with two names is found, and one name per code is proposed", canon.get("code") == "codigo_cliente" and spelt in canon.get("why", "") and XA["variant_of"] in canon.get("why", "") and code in canon.get("why", ""), canon.get("why"))
    check("7. the customer is the name, the code is its code (not “Código Cliente” as the customer)", MA["dataset"]["draft"]["roles"].get("customerCode") == "codigo_cliente" and MA["dataset"]["draft"]["roles"].get("customer") not in (None, "codigo_cliente"), MA["dataset"]["draft"]["roles"])
    st, top = call("GET", f"/api/datasets/{A}/runs/{RUN_A}/table/out_top_customers?offset=0&limit=100")
    names = {r[0]: r for r in top.get("rows", [])}
    ndoc = top["columns"].index("documents") if "documents" in top.get("columns", []) else -1
    check("7. both spellings count as one customer in the top customers", spelt not in names and XA["variant_of"] in names and names[XA["variant_of"]][ndoc] == XA["variant_docs"], (XA["variant_of"] in names and names[XA["variant_of"]][ndoc], XA["variant_docs"]))
    st, csv = call("GET", f"/api/datasets/{A}/runs/{RUN_A}/export/out_documents")
    text = csv.decode("utf-8-sig") if isinstance(csv, bytes) else ""
    lines = text.splitlines()
    check("8. a clean table exports as CSV with every row", st == 200 and len(lines) == XA["kept"] + 1 and "Nº interno" in lines[0], (st, len(lines)))
    cells = [c for ln in lines for c in ln.replace('""', '"').split(",")]
    check("8. formula-like cells are exported inert (a leading apostrophe)", all(f"'{h}"[:12] in text.replace('""', '"') for h in XA["hostile"]) and not any(c.lstrip('"').startswith(("=", "@")) for c in cells),
          [c for c in cells if "SUM" in c or "HYPERLINK" in c][:3])
    # placement and lineage of a run's tables
    st, doc = call("POST", "/api/files", {"name": f"E2E guided {TAG}", "json": json.dumps({"tables": []})})
    DOC = doc["id"]
    st, pl = call("POST", f"/api/files/{DOC}/datasets/place", {"dataset": A, "run": RUN_A, "outputs": ["monthly", "documents"]})
    placed = {t["output"]: t for t in pl.get("placement", {}).get("tables", [])}
    check("9. tables are placed in a workbook", st == 200 and set(placed) == {"monthly", "documents"}, (st, pl))
    st, L = call("GET", f"/api/files/{DOC}/lineage?table={placed['documents']['table']}&row=5")
    L = L.get("lineage") or {}
    row = L.get("row") or {}
    orig = {o.get("key"): o for o in row.get("original") or []}
    clean = {c.get("key"): c for c in row.get("cleaned") or []}
    check("9. right-click a document: the steps, and the line in the file it came from", len(L.get("steps", [])) >= 5 and row.get("sourceRow") and orig and clean, (len(L.get("steps", [])), row.get("sourceRow")))
    check("9. the original line and the cleaned row are paired by column (dropped and derived columns apart)",
          ident(orig.get("no_interno", {}).get("value")) == ident(clean.get("no_interno", {}).get("value")) and "moeda" in orig and "moeda" not in clean and "net_amount" in clean and "net_amount" not in orig,
          (sorted(orig)[:6], sorted(clean)[:6]))
    st, L = call("GET", f"/api/files/{DOC}/lineage?table={placed['monthly']['table']}&row=2")
    g = (L.get("lineage") or {}).get("row") or {}
    month = next((x["value"] for x in g.get("group", [])), None)
    check("9. right-click a monthly total: which documents make it up", month in monthly and g.get("members", {}).get("count") == monthly[month]["documents"], (month, g.get("members")))
    st, rec = call("POST", "/api/recipes", {"dataset": A, "run": RUN_A, "name": RECIPE, "note": "first export"})
    REC = rec.get("recipe", {}).get("id")
    check("10. the steps are saved as a recipe", st == 201 and REC and rec["recipe"]["current"] == 1, (st, rec.get("error")))

    # ============================================================ 2. the corrected re-export, in the browser
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True, args=LAUNCH)
        page = browser.new_context(viewport={"width": 1600, "height": 1000}).new_page()
        errors = []
        page.on("pageerror", lambda e: errors.append(str(e)))
        page.on("dialog", lambda dl: dl.accept())
        shot = lambda n: page.screenshot(path=f"{OUT}/guided-{n}.png")  # noqa: E731
        page.goto(BASE + "/", wait_until="networkidle")
        page.wait_for_selector(".topbar", timeout=60_000)
        page.get_by_role("button", name="Guided import of a large export").click()
        page.wait_for_selector(".studio .dropzone", timeout=15_000)
        # the library's lists load after the drop zone shows: wait for them, do not race them
        for text in (NAME_A, RECIPE):
            try:
                page.locator(".studio").get_by_text(text).first.wait_for(timeout=15_000)
            except Exception:
                pass
        lib = page.inner_text(".studio")
        check("11. the Studio library lists the first file and the saved recipe", NAME_A in lib and RECIPE in lib)
        page.set_input_files(".studio input[type=file]", f"{OUT}/{NAME_B}.xlsx")
        page.wait_for_selector("aside[aria-label='Steps'] .step-row", timeout=300_000)
        page.wait_for_function("() => document.querySelector('.prepare-data .studio-table') && !document.querySelector('.pill.loading')", timeout=180_000)
        page.wait_for_selector(".match-card", timeout=30_000)
        card = page.inner_text(".match-card")
        check("12. the new file is recognised as the recipe's layout", RECIPE in card, card[:200])
        check("12. the drift is named: a missing column, a renamed one, a new one", "Ref. Cliente" in card and "Valor Total (AOA)" in card and "Observações" in card, card[:400])
        grid = page.inner_text(".prepare-data .studio-table")
        check("12. document numbers are shown as they are, not as quantities (100001, not 100,001)", "100001" in grid and "100,001" not in grid, grid[:160])
        shot("01-match")
        page.locator(".match-card button", has_text="What changed?").click()
        page.wait_for_selector(".match-card .layout-diff", timeout=60_000)
        diff = page.inner_text(".match-card .layout-diff")
        check("13. “What changed?” shows the header row moving and the columns", "3" in diff and "Valor Total" in diff and "Ref. Cliente" in diff, diff[:400])
        shot("02-what-changed")
        page.locator(".run-bar button.primary").click()
        page.wait_for_selector(".results .run-summary", timeout=600_000)
        summary = page.inner_text(".results .run-summary")
        check("14. the recipe's steps run on the new layout", f"{XB['rows'] - XA['cancelled']:,}" in summary, summary[:200])
        shot("03-results")
        page.locator(".studio-tabs button", has_text="Related").click()
        page.wait_for_selector(".related .relation-card", timeout=180_000)
        page.wait_for_function("() => !document.querySelector('.related .pill.loading')", timeout=180_000)
        rel = page.locator(".relation-card", has_text=NAME_A).first
        cmp = rel.locator(".suggestion button", has_text="Compare")
        check("15. the first file is found as related, with a keyed comparison offered", cmp.count() == 1)
        before = page.evaluate("() => document.querySelector('.merge-card')?.dataset.merge ?? ''")
        cmp.first.click()
        page.wait_for_function("(b) => { const c = document.querySelector('.merge-card'); return c && c.dataset.merge !== b; }", arg=before, timeout=300_000)
        page.wait_for_timeout(1500)
        mc = page.locator(".merge-card").first
        text = mc.inner_text()
        check("16. the comparison names its key by column and tells what it found",
              "matched on Nº interno here = Nº interno there" in text and f"{XC['status']} “Aberta” → “Fechada”" in text and "+35,002 AOA" in text and "Observações (here), Ref. Cliente (there)" in text, text.replace("\n", " | ")[:600])
        shot("04-compared")
        place = mc.locator(".place-card")
        check("17. the comparison can be placed, in a new workbook by default", place.count() == 1 and place.locator("input[type=radio]").first.is_checked())
        place.locator("button.primary").click()
        page.wait_for_function("() => { const c = document.querySelector('.merge-card .place-card'); return c && [...c.querySelectorAll('.green-text, .err')].some(e => /Placed|error|failed|denied/i.test(e.textContent)); }", timeout=120_000)
        msg = place.locator(".green-text, .err").first.inner_text()
        check("17. the five comparison tables are placed", msg.startswith("Placed 5 tables"), msg)
        page.click("button[aria-label='Close the guided import']")
        page.wait_for_timeout(2500)
        imported = page.evaluate("() => [...window.__gw.getState().importedTables.entries()].map(([k, v]) => ({ table: k, name: v.name ?? '' }))")
        check("18. the workbook opens with the placed tables", len(imported) == 5, imported)
        seen = {}
        for want in imported:
            page.evaluate("""(t) => {
              const meta = window.__gw.getState().tables.get(t);
              const r = Math.min((meta.header_rows ?? 1) + 1, meta.rows - 1);
              window.__gw.selectCell(t, r, 0);
              document.querySelector('.canvas-host').dispatchEvent(new CustomEvent('gw-contextmenu', { detail: { x: 700, y: 400, hit: { kind: 'cell', table: t, r, c: 0 } } }));
            }""", want["table"])
            page.wait_for_timeout(500)
            hit = page.locator(".context-menu .menu-item", has_text="How was this")
            if not hit.count():
                page.keyboard.press("Escape")
                continue
            hit.first.click()
            page.wait_for_selector(".modal.lineage .lineage-chain", timeout=30_000)
            page.wait_for_timeout(800)
            seen[want["name"]] = page.inner_text(".modal.lineage")
            if want["name"].startswith("Missing"):
                shot("05-lineage-missing")
            page.keyboard.press("Escape")
            page.wait_for_timeout(300)
        check("19. right-click on every placed table: “How was this made?” explains the comparison", len(seen) == 5 and all("Compared with" in b and NAME_A in b for b in seen.values()), sorted(seen))
        miss = next((b for n, b in seen.items() if n.startswith("Missing")), "")
        check("19. a document missing here is traced to its line in the first file", f"The line in “{NAME_A}" in miss, miss[:200])
        chg = next((b for n, b in seen.items() if n.startswith("Every difference")), "")
        check("19. a changed document shows the comparison row apart from the file's line", "The row in this table" in chg and "The line in the file" in chg)
        check("20. no uncaught errors in the page", not errors, "; ".join(errors[:2])[:200])
        browser.close()

    # ============================================================ 3. the comparison is exact
    st, lst = call("GET", "/api/datasets")
    B = next(x["id"] for x in lst["datasets"] if x["file"] == f"{NAME_B}.xlsx")
    st, d = call("GET", f"/api/datasets/{B}")
    MB = d["dataset"]
    check("21. the new file used the recipe, its header found on row 3", (MB.get("match") or {}).get("recipe") == REC and (MB["draft"].get("recipe") or {}).get("id") == REC and MB["draft"]["steps"][0].get("row") == XB["header_row"],
          (MB.get("match", {}).get("recipe"), MB["draft"].get("recipe"), MB["draft"]["steps"][0].get("row")))
    mg = MB["merges"][0]
    MID = mg["id"]
    check("21. the comparison records its files, runs and key", mg["kind"] == "compare" and mg.get("run") and mg.get("otherRun") and mg.get("keyLabels", {}).get("a") == "Nº interno", {k: mg.get(k) for k in ("kind", "run", "otherRun", "keyLabels")})
    fields = {x["field"]: x["documents"] for x in table(B, None, "fields", MID)}
    check("22. exactly the logged edits differ, column by column", fields == {"Status": XC["status"], "Valor Total": XC["amount"]}, fields)
    status = table(B, None, "status", MID)
    check("22. the status movements", len(status) == 1 and status[0]["there"] == "Aberta" and status[0]["here"] == "Fechada" and status[0]["documents"] == XC["status"], status)
    changes = table(B, None, "changes", MID)
    amt = {ident(c["document"]): float(c["here"]) - float(c["there"]) for c in changes if c["field"] == "Valor Total"}
    check("22. every corrected amount, with its exact change", {k: round(v, 2) for k, v in amt.items()} == {k: round(v, 2) for k, v in XC["corrected"].items()},
          [(k, amt.get(k), v) for k, v in XC["corrected"].items() if not near(amt.get(k), v)][:3])
    shut = {ident(c["document"]) for c in changes if c["field"] == "Status"}
    check("22. every document closed since the first export", shut == {str(x) for x in XC["closed"]}, len(shut))
    here = sorted(int(float(x["document"])) for x in table(B, None, "only_here", MID))
    there = sorted(int(float(x["document"])) for x in table(B, None, "only_there", MID))
    check("23. documents only in the new file, and missing from it", here == XC["only_here"] and there == XC["only_there"], (here[:3], there[:3]))
    # the rows of the placed comparison point at the right file
    pm = next((p for p in MB["placements"] if p.get("merge") == MID), {})
    WB = pm.get("doc")
    tabs = {t["output"]: t["table"] for t in pm.get("tables", [])}
    check("24. the placement in the workbook records the comparison", WB and set(tabs) == {"fields", "status", "changes", "only_here", "only_there"}, tabs)
    st, L = call("GET", f"/api/files/{WB}/lineage?table={tabs.get('only_there', -1)}&row=0")
    row = (L.get("lineage") or {}).get("row") or {}
    o = {x.get("key"): x.get("value") for x in row.get("original") or []}
    check("24. a missing document's lineage opens its line in the first file", st == 200 and row.get("file", "").startswith(NAME_A) and int(float(o.get("no_interno"))) in XC["only_there"], (st, row.get("file"), o.get("no_interno")))
    st, L = call("GET", f"/api/files/{WB}/lineage?table={tabs.get('changes', -1)}&row=0")
    row = (L.get("lineage") or {}).get("row") or {}
    check("24. a changed document's lineage opens its line in the new file", st == 200 and row.get("sourceRow") and not row.get("file"), (st, row.get("sourceRow"), row.get("file")))

    # ============================================================ 4. automatic, guarded, deleted
    blocked = [s["text"] for s in (MB.get("match") or {}).get("summary", []) if s["level"] == "error"]
